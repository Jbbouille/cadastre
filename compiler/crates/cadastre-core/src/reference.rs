fn grammar_section(out: &mut String, grammar: &Value) {
    out.push_str(
        "## 1. Syntax\n\n\
         Notation: `a b` sequence, `a | b` choice, `a?` optional, `a*` zero or more, `a+` one or more, \
         `( )` grouping, `\"x\"` keyword or punctuation, `/x/` regular expression, `name:x` a named \
         part, `~x` written right after the previous token, without space. Whitespace and comments \
         (`comment`) may appear between any two tokens. Rules starting with `_` only group \
         alternatives.\n",
    );
    let rules = grammar["rules"].as_object().expect("rules");
    // Precedences of the operators, from the tightest.
    let mut precedences: Vec<(i64, &str)> = rules
        .iter()
        .filter(|(_, rule)| rule["type"].as_str().is_some_and(|t| t.starts_with("PREC")))
        .filter_map(|(name, rule)| Some((rule["value"].as_i64()?, name.as_str())))
        .collect();
    precedences.sort_by(|a, b| b.cmp(a));
    let operators: Vec<String> = precedences.iter().map(|(_, name)| format!("`{name}`")).collect();
    let _ = writeln!(out, "\nOperators bind from the tightest: {}.", operators.join(", "));
    let width = rules.keys().map(String::len).max().unwrap_or(0);
    for (name, rule) in rules {
        if let Some((_, title)) = SECTIONS.iter().find(|(first, _)| first == name) {
            if name != SECTIONS[0].0 {
                out.push_str("```\n");
            }
            let _ = write!(out, "\n### {title}\n\n```\n");
        }
        let _ = writeln!(out, "{name:width$} ::= {}", ebnf(rule, Context::Top));
    }
    out.push_str("```\n\n");
}

/// Where an expression is written: what it must be wrapped in.
#[derive(Clone, Copy, PartialEq, Eq)]
enum Context {
    Top,
    Sequence,
    Postfix,
}

fn ebnf(rule: &Value, context: Context) -> String {
    let wrap = |text: String, needed: bool| if needed { format!("({text})") } else { text };
    match rule["type"].as_str().unwrap_or_default() {
        "SEQ" => {
            let members: Vec<String> = members(rule).iter().map(|m| ebnf(m, Context::Sequence)).collect();
            wrap(members.join(" "), context == Context::Postfix && members.len() > 1)
        }
        "CHOICE" => {
            let all = members(rule);
            let optional = all.iter().any(|m| m["type"] == "BLANK");
            let others: Vec<&Value> = all.iter().filter(|m| m["type"] != "BLANK").collect();
            if optional {
                let inner = match others.as_slice() {
                    [one] => ebnf(one, Context::Postfix),
                    _ => format!("({})", alternatives(&others)),
                };
                format!("{inner}?")
            } else {
                wrap(alternatives(&others), context != Context::Top && others.len() > 1)
            }
        }
        "REPEAT" => format!("{}*", ebnf(&rule["content"], Context::Postfix)),
        "REPEAT1" => format!("{}+", ebnf(&rule["content"], Context::Postfix)),
        "FIELD" => {
            format!("{}:{}", rule["name"].as_str().unwrap_or_default(), ebnf(&rule["content"], Context::Postfix))
        }
        "STRING" => format!("{:?}", rule["value"].as_str().unwrap_or_default()),
        "PATTERN" => format!("/{}/", rule["value"].as_str().unwrap_or_default()),
        "SYMBOL" => rule["name"].as_str().unwrap_or_default().to_owned(),
        "BLANK" => "()".to_owned(),
        "IMMEDIATE_TOKEN" => format!("~{}", ebnf(&rule["content"], Context::Postfix)),
        // Precedences, tokens and aliases do not change the language.
        _ => ebnf(&rule["content"], context),
    }
}

fn members(rule: &Value) -> Vec<Value> {
    rule["members"].as_array().cloned().unwrap_or_default()
}

fn alternatives(members: &[&Value]) -> String {
    members.iter().map(|m| ebnf(m, Context::Sequence)).collect::<Vec<_>>().join(" | ")
}

