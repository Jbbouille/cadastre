fn plans_section(out: &mut String) {
    out.push_str("## 3. Plans\n\n### Formats of `render`\n\n| Format | Output |\n|---|---|\n");
    for (format, doc) in vocabulary::FORMATS {
        let _ = writeln!(out, "| `{format}` | {doc} |");
    }
    out.push_str("\n### Options of `render`\n\n");
    let (hints, options): (Vec<OptionDef>, Vec<OptionDef>) =
        vocabulary::RENDER_OPTIONS.iter().copied().partition(|o| vocabulary::LAYOUT_HINTS.contains(&o.key));
    options_table(out, &options);
    out.push_str(
        "\n#### Layout hints\n\nOptions that only steer where a diagram puts things, when the default layout does \
         not read well; the layout engine decides, and a hint it cannot follow is ignored. Rarely needed.\n\n",
    );
    options_table(out, &hints);
    out.push_str(
        "\n### Attributes of `view`\n\nFor the readers of the view: shown by the site, the previews and the playground.\n\n",
    );
    options_table(out, vocabulary::VIEW_ATTRIBUTES);
    out.push_str(
        "\n### Values of `edge_labels`\n\nThese words, or any key written on the links or the connectors of the \
         edge, or on the two ends of the references it draws (`circuit_id`, `label`).\n\n| Label | Shows |\n|---|---|\n",
    );
    for (label, doc) in vocabulary::EDGE_LABELS {
        let _ = writeln!(out, "| `{label}` | {doc} |");
    }

    out.push_str("\n### Edge selectors\n\nThe selectors of `edges`: a list of layers (`[flow, auth]`), `lift(…)`, `follow(…)`, or a relation:\n\n");
    let relations: Vec<String> = crate::view::reference_keys().into_iter().map(|k| format!("`{k}`")).collect();
    let _ = writeln!(out, "- reference keys: {};", relations.join(", "));
    out.push_str("- `parent`: containment, from a resource to its parent;\n");
    let connectors: Vec<String> = schema::expand("connector").iter().map(|k| format!("`{k}`")).collect();
    let _ = writeln!(out, "- connector kinds: {}, or the group `connector`.\n", connectors.join(", "));
    out.push_str("#### Options of `edges`\n\n");
    options_table(out, vocabulary::EDGES_OPTIONS);
    out.push_str("\n#### Options of `lift`\n\n");
    options_table(out, vocabulary::LIFT_OPTIONS);
    out.push_str("\n#### Options of `follow`\n\n");
    options_table(out, vocabulary::FOLLOW_OPTIONS);

    out.push_str(
        "\n### Levels of `group-by`\n\nA kind, a group, or a reference key (`owner`, `on`…), from the broadest to \
         the finest level: `group-by site > subnet`.\n\n\
         ### Filters\n\nThe keys of the resources and links, and these pseudo-attributes. Order comparisons \
         (`<`, `<=`, `>`, `>=`) need a number or a version on the right, on a `number`, `semver` or `version` \
         key, a free key, `port` or `step`; free keys are compared on their raw text, in order when the value \
         is a number or a version. The first key of a `select` or `kind` filter must exist for the filtered \
         kinds. On edges, the right side of a comparison may be a path starting with \
         `source` or `target` (`source.ancestor(system) != target.ancestor(system)`): `=` holds when both sides \
         share a value, `!=` when they have values and share none, and a side without value makes the \
         comparison false.\n\n\
         | Pseudo-attribute | On | Meaning |\n|---|---|---|\n",
    );
    for (name, on, doc) in vocabulary::PSEUDO {
        let _ = writeln!(out, "| `{name}` | {} | {doc} |", styled(*on));
    }

    out.push_str(
        "\n### Zones\n\nA zone is a frame of the view, at the top level, gathering the nodes and frames it names \
         or that match its filter, taken out of their `group-by` frames; a frame comes with its content. Its \
         name designates it in `stack` and `cross`. Properties of its frame:\n\n",
    );
    options_table(out, vocabulary::ZONE_PROPERTIES);
    out.push_str("\n### Style properties\n\n| Property | Values | On | Default | Meaning |\n|---|---|---|---|---|\n");
    for (property, on) in vocabulary::STYLE_PROPERTIES {
        let _ = writeln!(
            out,
            "| `{}` | {} | {} | {} | {} |",
            property.key,
            code(&values_text(property.values)),
            styled(*on),
            default(property),
            property.doc
        );
    }

    out.push_str(
        "\n### Checks\n\nA `check` selects nodes (`select`) or edges (`edges`, every kind being selected \
         without `select`), as a view does, and states the expected result: on the edges when it has an \
         `edges` clause, on the nodes otherwise. `cadastre check` runs the checks of a valid model; a failing \
         check lists the offending nodes or edges.\n\n| Expectation | Holds when |\n|---|---|\n",
    );
    for (expectation, doc) in vocabulary::EXPECTATIONS {
        let _ = writeln!(out, "| `expect {expectation}` | {doc} |");
    }
    out.push_str("\n#### Attributes of `check`\n\n");
    options_table(out, vocabulary::CHECK_ATTRIBUTES);
}

fn options_table(out: &mut String, options: &[OptionDef]) {
    out.push_str("| Option | Values | Default | Meaning |\n|---|---|---|---|\n");
    for option in options {
        let _ = writeln!(
            out,
            "| `{}` | {} | {} | {} |",
            option.key,
            code(&values_text(option.values)),
            default(option),
            option.doc
        );
    }
}

fn values_text(values: Values) -> String {
    match values {
        Values::Resource(kinds) => format!("ref({})", kinds.replace('|', " | ")),
        other => vocabulary::values_text(other),
    }
}

fn default(option: &OptionDef) -> String {
    if option.default.is_empty() { String::new() } else { format!("`{}`", option.default) }
}

fn styled(on: Styled) -> &'static str {
    match on {
        Styled::Nodes => "nodes",
        Styled::Edges => "edges",
        Styled::Both => "nodes and edges",
    }
}

/// Inline code in a table cell: its `|` escaped.
fn code(text: &str) -> String {
    format!("`{}`", text.replace('|', "\\|"))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn reference_is_up_to_date() {
        let root = concat!(env!("CARGO_MANIFEST_DIR"), "/../../..");
        let grammar = std::fs::read_to_string(format!("{root}/grammar/src/grammar.json")).unwrap();
        let generated = markdown(&serde_json::from_str(&grammar).unwrap());
        let path = format!("{root}/docs/reference.md");
        if std::env::var_os("UPDATE_REFERENCE").is_some() {
            std::fs::write(&path, &generated).unwrap();
        }
        let committed = std::fs::read_to_string(&path).unwrap_or_default().replace("\r\n", "\n");
        assert!(
            committed == generated,
            "docs/reference.md is out of date: run `UPDATE_REFERENCE=1 cargo test -p cadastre-core reference`"
        );
    }
}
