//! `docs/reference.md`: the strict reference of the language, generated from the grammar
//! (`grammar/src/grammar.json`), the schema ([`crate::schema`]) and the vocabulary of plans
//! ([`crate::vocabulary`]). A test compares it with the committed file; `UPDATE_REFERENCE=1 cargo
//! test -p cadastre-core reference` rewrites it.

use std::fmt::Write;

use serde_json::Value;

use crate::schema::{self, AttrDef, Card, Ty};
use crate::vocabulary::{self, OptionDef, Styled, Values};

/// Sections of the grammar, by their first rule.
const SECTIONS: &[(&str, &str)] =
    &[("source_file", "Registry"), ("_reference", "Values"), ("identifier", "Tokens"), ("view", "Plans")];

fn markdown(grammar: &Value) -> String {
    let mut out = String::new();
    out.push_str(
        "# Cadastre reference\n\n\
         <!-- Generated by `UPDATE_REFERENCE=1 cargo test -p cadastre-core reference`: do not edit. -->\n\n\
         The exact language: its syntax, from the grammar (`grammar/src/grammar.json`), and what the \
         compiler knows, from its tables (`schema.rs`, `vocabulary.rs`). The [guide](guide.md) explains \
         it with examples.\n\n\
         A key of a resource or a link that is not listed here is a **free key**: accepted, not \
         checked, compared on its raw text in filters, never proposed by completion.\n\n",
    );
    grammar_section(&mut out, grammar);
    kinds_section(&mut out);
    plans_section(&mut out);
    out
}

