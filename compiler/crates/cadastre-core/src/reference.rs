fn kinds_section(out: &mut String) {
    out.push_str(
        "## 2. Resources and links\n\n\
         Types: `string`; `number`; `semver` (`1.2.0`, `v2.0.1-rc1`); `version` (a semver, a number or a \
         string); `ip`; `cidr`; `host name` (`labels.example.com`, bare or quoted); `a | b` one of these \
         words; `ref(k)` the name of a resource of kind or group `k`. A list is written `[a, b]`; a \
         single value may be written without brackets.\n\n\
         ### Keys of every resource\n\n",
    );
    keys_table(out, schema::RESOURCE_KEYS);
    out.push_str(
        "\n`parent: <name>`, on a resource declared at the root, places it in a resource of one of its \
         parent kinds (below), as if it were nested in its block; never on a nested resource, nor on a kind \
         always at the root.\n",
    );
    out.push_str("\n### Keys of links\n\nOn `->` links, in their block.\n\n");
    keys_table(out, schema::LINK_KEYS);
    out.push_str("\n### Kinds\n\n");
    let (within, kinds): (Vec<&schema::KindDef>, Vec<&schema::KindDef>) = schema::KINDS.iter().partition(|k| k.within);
    for kind in kinds {
        kind_section(out, kind);
    }
    out.push_str(
        "### Kinds within a resource\n\nDetails of a resource, declared in its block only: an interface of a \
         device, a component of an app, a channel of a broker, a participant of a process. Resources like the \
         others (named, resolved, referenced, renamed), listed here apart from the kinds of the map.\n\n",
    );
    for kind in within {
        kind_section(out, kind);
    }
    out.push_str("### Groups\n\nA group stands for its kinds wherever a kind is expected (`ref(transit)`, `select network_device`).\n\n| Group | Kinds |\n|---|---|\n");
    for (group, kinds) in schema::GROUPS {
        let kinds: Vec<String> = kinds.iter().map(|k| format!("`{k}`")).collect();
        let _ = writeln!(out, "| `{group}` | {} |", kinds.join(", "));
    }
    out.push('\n');
}

fn kind_section(out: &mut String, kind: &schema::KindDef) {
    let _ = write!(out, "#### `{}`\n\n", kind.name);
    let parents: Vec<String> =
        kind.parents.iter().map(|p| if *p == "none" { "root".to_owned() } else { format!("`{p}`") }).collect();
    let _ = write!(out, "In: {}.", parents.join(", "));
    if kind.owner_required {
        out.push_str(" `owner` required, after inheritance, unless `scope: external`.");
    }
    if let Some(ends) = kind.connector {
        let _ = write!(out, " Connector between its two `{ends}`.");
    }
    out.push_str("\n\n");
    if kind.attrs.is_empty() {
        out.push_str("No keys of its own.\n\n");
    } else {
        keys_table(out, kind.attrs);
        out.push('\n');
    }
}

fn keys_table(out: &mut String, attrs: &[AttrDef]) {
    out.push_str("| Key | Type | Count | Required |\n|---|---|---|---|\n");
    for attr in attrs {
        let card = match attr.card {
            Card::One => "one".to_owned(),
            Card::OneOrMore => "one or more".to_owned(),
            Card::Many => "list".to_owned(),
            Card::Exactly(n) => format!("exactly {n}"),
        };
        let required = if attr.required { "yes" } else { "" };
        let _ = writeln!(out, "| `{}` | {} | {card} | {required} |", attr.key, code(&type_text(attr.ty)));
    }
}

fn type_text(ty: Ty) -> String {
    match ty {
        Ty::Symbol(values) => values.join(" | "),
        Ty::String => "string".to_owned(),
        Ty::Strings => "string, or list of strings".to_owned(),
        Ty::Number => "number".to_owned(),
        Ty::Semver => "semver".to_owned(),
        Ty::Version => "version".to_owned(),
        Ty::Ip => "ip".to_owned(),
        Ty::Cidr => "cidr".to_owned(),
        Ty::Host => "host name".to_owned(),
        Ty::Url => "url (string)".to_owned(),
        Ty::Bandwidth => "bandwidth".to_owned(),
        Ty::Spdx => "spdx (string)".to_owned(),
        Ty::Ref(union) => format!("ref({})", union.replace('|', " | ")),
        Ty::Pattern(pattern) => format!("pattern(\"{}\")", pattern.source),
    }
}

