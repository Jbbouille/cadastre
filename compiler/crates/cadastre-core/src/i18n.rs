//! The languages of what Cadastre writes for its readers: the site, the words of the diagrams.
//!
//! The language itself stays in English, as every language does (`site`, `server`, `on`); the
//! contents of a project (labels, descriptions, titles) are in the language of its authors. What
//! is translated is what the tools say around them. English is the key of every text, so that
//! a text missing from a catalogue falls back to it, readable.

/// A language of the readers. `En` is the default and the key of the catalogues.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Hash)]
pub enum Language {
    #[default]
    En,
    Fr,
}

impl Language {
    /// The languages known, by their code.
    pub const ALL: &[Language] = &[Language::En, Language::Fr];

    /// A language from its code (`en`, `fr`, `fr-FR`).
    pub fn parse(code: &str) -> Option<Self> {
        let code = code.trim().to_ascii_lowercase();
        let main = code.split(['-', '_']).next().unwrap_or_default();
        match main {
            "en" => Some(Self::En),
            "fr" => Some(Self::Fr),
            _ => None,
        }
    }

    pub fn code(self) -> &'static str {
        match self {
            Self::En => "en",
            Self::Fr => "fr",
        }
    }

    /// The text in this language, from its English; the English when the catalogue has none.
    pub fn text(self, english: &'static str) -> &'static str {
        let catalogue: &[(&str, &str)] = match self {
            Self::En => return english,
            Self::Fr => FR,
        };
        catalogue.iter().find(|(en, _)| *en == english).map_or(english, |(_, text)| text)
    }

    /// The plural of a word counted: `n` of them.
    pub fn plural(self, english_singular: &'static str, n: u64) -> String {
        let singular = self.text(english_singular);
        if n == 1 {
            return singular.to_owned();
        }
        match self {
            Self::En => crate::render::plural(singular),
            Self::Fr => {
                if singular.ends_with('s') || singular.ends_with('x') {
                    singular.to_owned()
                } else {
                    format!("{singular}s")
                }
            }
        }
    }
}

