#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn codes_texts_and_plurals() {
        assert_eq!(Language::parse("fr-FR"), Some(Language::Fr));
        assert_eq!(Language::parse("EN"), Some(Language::En));
        assert_eq!(Language::parse("de"), None);
        assert_eq!(Language::Fr.text("Views"), "Vues");
        assert_eq!(Language::Fr.text("not in the catalogue"), "not in the catalogue");
        assert_eq!(Language::En.plural("check", 2), "checks");
        assert_eq!(Language::Fr.plural("check", 2), "vérifications");
        assert_eq!(Language::Fr.plural("check", 1), "vérification");
        assert_eq!(Language::Fr.plural("resource", 3), "ressources");
    }

    #[test]
    fn diagnostics_are_translated_by_templates() {
        let fr = Language::Fr;
        assert_eq!(fr.message("unknown attribute: verison"), "attribut inconnu : verison");
        assert_eq!(fr.message("did you mean `version`?"), "vouliez-vous dire `version` ?");
        // A summary inside a message: translated in turn, the names left alone.
        assert_eq!(
            fr.message("check owners failed: 2 nodes selected, none expected: shop.front, shop.back"),
            "vérification owners en échec : 2 nœuds sélectionné(s), aucun attendu : shop.front, shop.back"
        );
        assert_eq!(
            fr.message("check x failed: no edge selected, at least one expected"),
            "vérification x en échec : aucune arête sélectionné(s), au moins un attendu"
        );
        assert_eq!(
            fr.message("view flows: zone dmz: web01 is not in the view"),
            "vue flows : zone dmz : web01 n'est pas dans la vue"
        );
        // Not in the catalogue: as it is. English: as it is.
        assert_eq!(fr.message("something else entirely"), "something else entirely");
        assert_eq!(Language::En.message("unknown attribute: x"), "unknown attribute: x");
        // Every template is a valid regex, and its French numbers its parts.
        for (en, fr_text) in FR_MESSAGES {
            let parts = en.matches("{}").count();
            for i in 1..=parts {
                assert!(fr_text.contains(&format!("{{{i}}}")), "{en}: part {i} missing in {fr_text}");
            }
        }
    }

    #[test]
    fn every_french_text_keeps_the_placeholders_of_its_english() {
        for (en, fr) in FR {
            for placeholder in ["{n}", "{kind}", "{name}", "{where}", "{frame}", "{version}", "{example}"] {
                assert_eq!(en.contains(placeholder), fr.contains(placeholder), "{en}");
            }
        }
    }
}
