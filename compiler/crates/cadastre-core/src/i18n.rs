impl Language {
    /// A diagnostic message or help in this language: the English is matched against the
    /// templates of the catalogue (`{}` standing for a name, a value, a list), the French
    /// template filled with what was matched, each matched part translated in turn (a summary
    /// inside a message). A message no template matches stays as it is.
    pub fn message(self, text: &str) -> String {
        match self {
            Self::En => text.to_owned(),
            Self::Fr => translate(text, fr_templates(), 3),
        }
    }
}

/// A template compiled: its regex over the English, the French with `{1}`, `{2}`… for the parts.
struct Template {
    english: regex_lite::Regex,
    french: &'static str,
}

fn fr_templates() -> &'static [Template] {
    static TEMPLATES: std::sync::OnceLock<Vec<Template>> = std::sync::OnceLock::new();
    TEMPLATES.get_or_init(|| {
        let mut templates: Vec<(&str, &str)> = FR_MESSAGES.to_vec();
        // The most specific first: the templates with the most literal text.
        let literal = |t: &str| t.len() - t.matches('{').count() * 2;
        templates.sort_by_key(|(en, _)| std::cmp::Reverse(literal(en)));
        templates.into_iter().map(|(en, fr)| Template { english: template_regex(en), french: fr }).collect()
    })
}

/// The regex of an English template: its literal parts escaped, each `{}` or `{name}` a part
/// matched; braces around anything else (`{ reply }`) are literal.
fn template_regex(template: &str) -> regex_lite::Regex {
    let mut pattern = String::from("(?s)^");
    let mut rest = template;
    let mut parts = 0;
    while let Some(start) = rest.find('{') {
        let Some(close) = rest[start..].find('}') else { break };
        let end = start + close + 1;
        let inside = &rest[start + 1..end - 1];
        if !inside.chars().all(|c| c.is_ascii_alphanumeric() || c == '_') {
            // A literal brace: kept, the search goes on after it.
            pattern.push_str(&regex_lite::escape(&rest[..end]));
            rest = &rest[end..];
            continue;
        }
        pattern.push_str(&regex_lite::escape(&rest[..start]));
        pattern.push_str("(.+?)");
        parts += 1;
        rest = &rest[end..];
    }
    pattern.push_str(&regex_lite::escape(rest));
    pattern.push('$');
    // The last part takes what is left (a list, a reason, or nothing), the others the shortest
    // text.
    if parts > 0 && rest.is_empty() {
        let at = pattern.rfind("(.+?)").expect("a part");
        pattern.replace_range(at..at + 5, "(.*)");
    }
    regex_lite::Regex::new(&pattern).expect("a valid template")
}

fn translate(text: &str, templates: &[Template], depth: usize) -> String {
    if depth == 0 {
        return text.to_owned();
    }
    for template in templates {
        let Some(captures) = template.english.captures(text) else { continue };
        let mut out = template.french.to_owned();
        for (i, part) in captures.iter().skip(1).enumerate() {
            let part = part.map_or("", |m| m.as_str());
            out = out.replace(&format!("{{{}}}", i + 1), &translate(part, templates, depth - 1));
        }
        return out;
    }
    text.to_owned()
}

